"""Private document storage. Business code depends on the DocumentStorage protocol only.

LocalDocumentStorage keeps files in a private directory with owner-only permissions.
Keys are generated by the server (random UUIDs), never taken from user input.
Production should use an encrypted, private object store (e.g. S3 with SSE in
af-south-1) behind the same interface (Stage 18).
"""

import os
import uuid
from pathlib import Path
from typing import Protocol


class DocumentNotFoundError(Exception):
    pass


class DocumentStorage(Protocol):
    def save(self, data: bytes) -> str: ...

    def read(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None: ...


class LocalDocumentStorage:
    def __init__(self, root: Path) -> None:
        self._root = root.resolve()
        self._root.mkdir(parents=True, exist_ok=True, mode=0o700)

    def _path(self, key: str) -> Path:
        # Keys are UUID hex strings; anything else is rejected (no path traversal).
        try:
            uuid.UUID(hex=key)
        except ValueError as exc:
            raise DocumentNotFoundError(key) from exc
        return self._root / key[:2] / key

    def save(self, data: bytes) -> str:
        key = uuid.uuid4().hex
        path = self._path(key)
        path.parent.mkdir(exist_ok=True, mode=0o700)
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
        return key

    def read(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError as exc:
            raise DocumentNotFoundError(key) from exc

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


class InMemoryDocumentStorage:
    """Used by automated tests."""

    def __init__(self) -> None:
        self.files: dict[str, bytes] = {}

    def save(self, data: bytes) -> str:
        key = uuid.uuid4().hex
        self.files[key] = data
        return key

    def read(self, key: str) -> bytes:
        if key not in self.files:
            raise DocumentNotFoundError(key)
        return self.files[key]

    def delete(self, key: str) -> None:
        self.files.pop(key, None)
